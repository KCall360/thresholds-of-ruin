"""Compare command re-execution from the same ordinary saved-game boundary.

This is audited envelope equivalence, never byte-exact replay. The caller must
supply full chronological ``authoritative_records`` and the evidence surfaces it
wants compared. Every supplied field is compared, including unknown fields. Only
new journal EntryId UUIDs, receipt request UUIDs, advancement session-stream
UUIDs at the two reviewed paths, and the explicitly typed references below are mapped.
Saved privacy salts, branches, public opaque handles, all other request-ID
locations, diagnostic segment IDs, gameplay, RNG, costs, progression, and event
order remain strict.

``initial_history_sequence`` defaults to zero (the route campaign's initial save
has no accepted commands). If supplied, its accepted prefix is compared exactly,
including EntryIds. Source-free restoration of already accepted history should
use the existing exact comparator, not this new-command equivalence helper.
No input is modified, no field is omitted, and the full mapping is returned.
"""
import copy
from uuid import UUID


