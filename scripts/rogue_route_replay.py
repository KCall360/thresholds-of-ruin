def _pointer(path):
    return '/' + '/'.join(str(part).replace('~', '~0').replace('/', '~1') for part in path)


def _lookup(value, path):
    for part in path:
        value = value[part]
    return value


def _locations(value, pattern, path=()):
    if not pattern:
        yield path, value
    elif pattern[0] == '*':
        if isinstance(value, list):
            for index, item in enumerate(value):
                yield from _locations(item, pattern[1:], (*path, index))
    elif isinstance(value, dict) and pattern[0] in value:
        yield from _locations(value[pattern[0]], pattern[1:], (*path, pattern[0]))


def _guarded(root, path, guards):
    for ancestor, field, values in guards:
        parts = ancestor.strip('/').split('/')
        concrete = tuple(path[index] if part == '*' else part for index, part in enumerate(parts))
        value = _lookup(root, concrete)
        if not isinstance(value, dict) or value.get(field) not in values:
            return False
    return True


def _uuid4(value):
    if not isinstance(value, str):
        return False
    try:
        parsed = UUID(value)
    except (ValueError, AttributeError):
        return False
    return parsed.version == 4 and str(parsed) == value


def _error(differences, side, path, kind, value, message):
    differences.append({'kind': kind, 'side': side, 'path': _pointer(path),
                        'value': copy.deepcopy(value), 'message': message})


def _normalize(raw, side, differences):
    normalized = copy.deepcopy(raw)
    records = raw.get('authoritative_records') if isinstance(raw, dict) else None
    if not isinstance(records, list):
        _error(differences, side, ('authoritative_records',), 'invalid_record_sequence', records,
               'A full chronological authoritative_records list is required.')
        return normalized, []
    prefix = raw.get('initial_history_sequence', 0)
    if type(prefix) is not int or not 0 <= prefix <= len(records):
        _error(differences, side, ('initial_history_sequence',), 'invalid_initial_boundary', prefix,
               'The accepted prefix must be an integer within the full record sequence.')
        return normalized, []
    identities, mappings = {}, []
    for index, record in enumerate(records):
        path = ('authoritative_records', index, 'entry', 'id')
        identity = (record.get('entry', {}).get('id') if isinstance(record, dict)
                    and isinstance(record.get('entry'), dict) else None)
        if not _uuid4(identity):
            _error(differences, side, path, 'invalid_entry_id', identity,
                   'Only canonical UUID v4 journal EntryIds are eligible for mapping.')
            continue
        if identity in identities:
            _error(differences, side, path, 'duplicate_entry_id', identity,
                   'A journal EntryId cannot define more than one record.')
            continue
        canonical = identity if index < prefix else f'entry:{index + 1}'
        row = {'kind': 'entry_id', 'sequence': index + 1, 'canonical': canonical, 'raw': identity,
               'definition_path': _pointer(path), 'reference_paths': [], 'retained_prefix': index < prefix}
        identities[identity] = row
        if index >= prefix:
            normalized['authoritative_records'][index]['entry']['id'] = canonical
            mappings.append(row)
    for pattern, nullable, guards in _RULES:
        for path, identity in _locations(raw, pattern.strip('/').split('/')):
            if path[0] == 'authoritative_records' and path[1] < prefix:
                continue
            if not _guarded(raw, path, guards) or (identity is None and nullable):
                continue
            if not isinstance(identity, str) or identity not in identities:
                _error(differences, side, path, 'unresolved_entry_reference', identity,
                       'An audited EntryId reference must name an entry in the full journal.')
                continue
            row = identities[identity]
            row['reference_paths'].append(_pointer(path))
            _lookup(normalized, path[:-1])[path[-1]] = row['canonical']
    mappings.extend(_normalize_requests(raw, normalized, prefix))
    mappings.extend(_normalize_streams(raw, normalized, prefix, side, differences))
    return normalized, mappings


def _normalize_requests(raw, normalized, prefix):
    identities, mappings = {}, []
    for path, identity in _locations(raw, ('authoritative_records', '*', 'receipt', 'request_id')):
        if not _uuid4(identity):
            continue
        receipt = _lookup(raw, path[:-1])
        # user is part of the server retry key; its value is still compared exactly.
        user = receipt.get('user')
        if not isinstance(user, str):
            continue
        key, sequence = (user, identity), path[1] + 1
        if key not in identities:
            retained = sequence <= prefix
            row = {'kind': 'request_id', 'sequence': sequence, 'raw': identity, 'user': user,
                   'canonical': identity if retained else f'request:{sequence}',
                   'definition_path': _pointer(path), 'reference_paths': []}
            identities[key] = row
            if not retained:
                mappings.append(row)
        row = identities[key]
        row['reference_paths'].append(_pointer(path))
        _lookup(normalized, path[:-1])[path[-1]] = row['canonical']
    return mappings


def _normalize_streams(raw, normalized, prefix, side, differences):
    identities, mappings = {}, []
    definition, guards = _STREAM_RULES[0]
    for path, identity in _locations(raw, definition.strip('/').split('/')):
        if not _guarded(raw, path, guards) or not _uuid4(identity):
            continue
        if identity not in identities:
            sequence = path[1] + 1
            retained = sequence <= prefix
            row = {'kind': 'advancement_stream', 'sequence': sequence, 'raw': identity,
                   'canonical': identity if retained else f'stream:{sequence}',
                   'definition_path': _pointer(path), 'reference_paths': []}
            identities[identity] = row
            if not retained:
                mappings.append(row)
    for pattern, guards in _STREAM_RULES:
        for path, identity in _locations(raw, pattern.strip('/').split('/')):
            if path[1] < prefix:
                continue
            if not _guarded(raw, path, guards) or not _uuid4(identity):
                continue
            if identity not in identities:
                _error(differences, side, path, 'unresolved_stream_reference', identity,
                       'A receipt stream must resolve to an audited journal action stream.')
                continue
            row = identities[identity]
            row['reference_paths'].append(_pointer(path))
            _lookup(normalized, path[:-1])[path[-1]] = row['canonical']
    return mappings


def _differences(left, right, path=()):
    if type(left) is not type(right):
        yield {'kind': 'type_mismatch', 'path': _pointer(path), 'left': copy.deepcopy(left),
               'right': copy.deepcopy(right)}
    elif isinstance(left, dict):
        for key in sorted(set(left) | set(right)):
            if key not in left or key not in right:
                yield {'kind': 'missing_field', 'path': _pointer((*path, key)),
                       'left_present': key in left, 'right_present': key in right,
                       'left': copy.deepcopy(left.get(key)), 'right': copy.deepcopy(right.get(key))}
            else:
                yield from _differences(left[key], right[key], (*path, key))
    elif isinstance(left, list):
        if len(left) != len(right):
            yield {'kind': 'length_mismatch', 'path': _pointer(path),
                   'left': len(left), 'right': len(right)}
        for index, (first, second) in enumerate(zip(left, right)):
            yield from _differences(first, second, (*path, index))
        for index in range(min(len(left), len(right)), max(len(left), len(right))):
            yield {'kind': 'missing_element', 'path': _pointer((*path, index)),
                   'left_present': index < len(left), 'right_present': index < len(right),
                   'left': copy.deepcopy(left[index]) if index < len(left) else None,
                   'right': copy.deepcopy(right[index]) if index < len(right) else None}
    elif left != right:
        yield {'kind': 'value_mismatch', 'path': _pointer(path),
               'left': copy.deepcopy(left), 'right': copy.deepcopy(right)}


def compare_execution(left, right):
    """Return complete differences plus the closed normalization schema and map.

    ``equal`` means all supplied artifacts match under the audited exception and
    all encountered audited definitions/references validate. ``raw_equal`` means
    structural JSON equality before mapping, including numeric/scalar types;
    neither result makes a claim about serialization bytes.
    """
    differences = []
    first, left_map = _normalize(left, 'left', differences)
    second, right_map = _normalize(right, 'right', differences)
    differences.extend(_differences(first, second))
    by_left = {(row['kind'], row['sequence']): row for row in left_map}
    by_right = {(row['kind'], row['sequence']): row for row in right_map}
    mapping = []
    for key in sorted(set(by_left) | set(by_right)):
        kind, sequence = key
        a, b = by_left.get(key), by_right.get(key)
        row = {
            'kind': kind, 'sequence': sequence, 'canonical': (a or b)['canonical'],
            'left': a['raw'] if a else None, 'right': b['raw'] if b else None,
            'definition_path': (a or b)['definition_path'],
            'left_reference_paths': a['reference_paths'] if a else [],
            'right_reference_paths': b['reference_paths'] if b else [],
        }
        if kind == 'request_id':
            row.update(left_user=a['user'] if a else None, right_user=b['user'] if b else None)
        mapping.append(row)
    return {'equal': not differences, 'raw_equal': not any(_differences(left, right)),
            'comparison': NORMALIZATION_SCHEMA['comparison'], 'differences': differences,
            'normalization_schema': copy.deepcopy(NORMALIZATION_SCHEMA), 'mapping': mapping}
